def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    if args.battles < 1:
        raise SystemExit("--battles debe ser mayor que cero.")
    if not 1 <= args.port <= 65535:
        raise SystemExit("--port debe estar entre 1 y 65535.")
    missing_commands = [command for command in ("git", "node", "npm") if shutil.which(command) is None]
    if missing_commands:
        raise RuntimeError(
            "Faltan comandos requeridos por Battle Lab: " + ", ".join(missing_commands) + "."
        )

    runtime_root = args.runtime_root.resolve()
    results_dir = (args.results_dir or runtime_root / "results").resolve()
    run_id = datetime.now(timezone.utc).strftime("phase1-%Y%m%dT%H%M%S-%fZ")
    run_root = runtime_root / "runs" / run_id
    logs_dir = run_root / "logs"
    local_replays = run_root / "replays"
    local_replays.mkdir(parents=True, exist_ok=True)
    commit = args.showdown_commit or read_showdown_commit()
    team_a = args.team_a.resolve().read_text(encoding="utf-8").strip() + "\n"
    team_b = args.team_b.resolve().read_text(encoding="utf-8").strip() + "\n"
    showdown_checkout = (args.showdown_checkout or runtime_root / "pokemon-showdown").resolve()
    overall = Progress(6, "Fase 1")
    started = time.monotonic()
    if args.skip_setup:
        if git_revision(showdown_checkout) != commit:
            raise RuntimeError(
                f"--skip-setup requiere Showdown en {commit}; "
                f"el checkout está en {git_revision(showdown_checkout)}."
            )
        if not (showdown_checkout / "node_modules").is_dir() or not (showdown_checkout / "dist" / "sim").is_dir():
            raise RuntimeError("--skip-setup requiere dependencias instaladas y Showdown compilado.")
        setup_timings = {"skipped": True}
    else:
        setup_timings = ensure_showdown_checkout(
            checkout=showdown_checkout,
            repository=args.showdown_repository,
            commit=commit,
            logs_dir=logs_dir,
        )
    install_runtime_config(showdown_checkout)
    overall.advance("Showdown fijado y compilado")

    validation_a = validate_team(showdown_checkout, args.format, team_a)
    validation_b = validate_team(showdown_checkout, args.format, team_b)
    overall.advance("Dos equipos M-C válidos")

    negative_validation = verify_illegal_team_is_rejected(showdown_checkout, args.format, team_a)
    overall.advance("Control ilegal rechazado correctamente")

    with running_showdown(showdown_checkout, args.port, logs_dir / "showdown-server.log") as server:
        overall.advance(f"Servidor privado listo en 127.0.0.1:{args.port}")
        battle_started = time.monotonic()
        battles, wins = asyncio.run(
            run_battles(
                port=args.port,
                battle_format=args.format,
                team_a=team_a,
                team_b=team_b,
                count=args.battles,
                timeout=args.battle_timeout,
                replay_dir=local_replays,
            )
        )
        resources = environment_snapshot(server.process.pid)
        startup_seconds = server.startup_seconds
        battle_seconds = time.monotonic() - battle_started
    server_log = (logs_dir / "showdown-server.log").read_text(encoding="utf-8", errors="replace")
    if "CRASH:" in server_log:
        raise RuntimeError(f"Showdown registró un fallo interno durante el smoke test.\n{tail(logs_dir / 'showdown-server.log')}")
    overall.advance(f"{len(battles)} combates WebSocket terminados")

    shutil.copytree(logs_dir, local_replays / "logs", dirs_exist_ok=True)
    results_dir.mkdir(parents=True, exist_ok=True)
    replay_archive = Path(
        shutil.make_archive(str(results_dir / f"{run_id}-replays"), "zip", root_dir=local_replays)
    )
    result_path = results_dir / f"{run_id}.json"
    total_seconds = time.monotonic() - started
    payload = {
        "schemaVersion": 1,
        "runId": run_id,
        "createdAt": utc_now(),
        "status": "passed",
        "projectCommit": git_revision(PROJECT_ROOT),
        "showdown": {
            "repository": args.showdown_repository,
            "commit": commit,
            "format": args.format,
            "port": args.port,
            "startupSeconds": startup_seconds,
            "setupTimings": setup_timings,
        },
        "teams": {
            "alpha": {
                "path": str(args.team_a.resolve()),
                "sha256": sha256_text(team_a),
                "validation": {"status": "valid", "message": validation_a or None},
            },
            "beta": {
                "path": str(args.team_b.resolve()),
                "sha256": sha256_text(team_b),
                "validation": {"status": "valid", "message": validation_b or None},
            },
            "negativeControl": negative_validation,
        },
        "battles": {
            "requested": args.battles,
            "completed": len(battles),
            "durationSeconds": round(battle_seconds, 3),
            "battlesPerMinute": round(len(battles) / battle_seconds * 60, 3),
            "wins": wins,
            "items": battles,
        },
        "environment": resources,
        "artifacts": {"replaysZip": str(replay_archive)},
        "totalDurationSeconds": round(total_seconds, 3),
    }
    atomic_json(result_path, payload)
    overall.advance(f"Resultado persistido en {result_path}")

    print("\n✅ Fase 1 superada")
    print(f"   Formato: {args.format}")
    print(f"   Combates: {len(battles)}/{args.battles}")
    print(f"   Rendimiento: {payload['battles']['battlesPerMinute']} combates/min")
    print(f"   Resultado: {result_path}")
    print(f"   Replays: {replay_archive}")
    return 0


